def homa(a, b, sensitivity, r=R, rl=RL):
    """Solve the forward model and return status followed by 12 values.

    a and b are beta_fraction**0.25 and beta_fraction**0.75.
    Outputs: ratio, glucose, insulin_specific, insulin_liver, cpeptide,
    cpeptide_secondary, secretion, secretion/1000, occupancy_peripheral,
    occupancy_liver, proinsulin, proinsulin_fraction.

    Uses regula falsi with bisection fallback and residual tolerance 5e-5.
    Statuses 11 and 12 indicate failure; -21 indicates the iteration limit.
    """
    out = [0.0] * 12
    lower_argument = a * 0.0
    upper_argument = 80.0 * a
    interpolate = True
    status = 0

    while True:
        secretion_low = uop(lower_argument) * b
        secretion_high = uop(upper_argument) * b
        out[11] = 0.0037681
        proinsulin = secretion_low * 0.0037823522816324193
        proinsulin = _divide(proinsulin, PIK * VPI)
        out[10] = proinsulin
        code, i0, i1, occupancy_p, occupancy_l = uss(
            secretion_low, r, rl, proinsulin
        )
        if code == 1:
            return (12, *out)
        flux_low = gflux(
            0.0, 4.85, occupancy_p, occupancy_l, proinsulin, r, rl, sensitivity
        )[0]

        out[11] = 0.07842049999999999
        proinsulin = 0.08509358118317518 * secretion_high
        proinsulin = _divide(proinsulin, PIK * VPI)
        out[10] = proinsulin
        code, i0, i1, occupancy_p, occupancy_l = uss(
            secretion_high, r, rl, proinsulin
        )
        if code == 1:
            return (12, *out)
        flux_high = gflux(
            80.0, 4.85, occupancy_p, occupancy_l, proinsulin, r, rl, sensitivity
        )[0]
        if flux_low < 0.0 or flux_high > 0.0:
            return (11, *out)

        lo = 0.0
        hi = 80.0
        if interpolate:
            glucose = _divide(-80.0 * flux_low + flux_high * 0.0,
                              flux_high - flux_low)
        else:
            glucose = 40.0
        out[1] = glucose

        converged = False
        for _ in range(250):
            secretion = uop(glucose * a) * b
            out[6] = secretion
            fraction = max(glucose * 0.000933155 + 0.0037681, 0.0)
            out[11] = fraction
            proinsulin = _divide(fraction, 1.0 - fraction) * secretion
            proinsulin = _divide(proinsulin, PIK * VPI)
            out[10] = proinsulin
            code, out[2], out[3], out[8], out[9] = uss(
                secretion, r, rl, proinsulin
            )
            if code == 1:
                return (12, *out)
            residual = gflux(
                glucose, 4.85, out[8], out[9], proinsulin, r, rl, sensitivity
            )[0]
            if 0.00005 > abs(residual):
                converged = True
                break
            if residual < 0.0:
                flux_high = residual
                hi = glucose
            else:
                flux_low = residual
                lo = glucose
            if interpolate:
                glucose = _divide(lo * flux_high - hi * flux_low,
                                  flux_high - flux_low)
            else:
                glucose = (lo + hi) * 0.5
            # Keep the next estimate when the iteration limit is reached.
            out[1] = glucose

        if converged:
            break
        if interpolate:
            interpolate = False
            continue
        status = -21
        break

    out[7] = out[6] / 1000.0
    out[4] = out[7] / 4.18 / 0.062
    out[5] = 0.053 * out[4] / 0.051
    fraction = max(out[1] * 0.000933155 + 0.0037681, 0.0)
    out[11] = fraction
    out[10] = _divide(_divide(fraction, 1.0 - fraction) * out[6], PIK * VPI)
    out[0] = _divide(4.85, out[1])
    return (status, *out)


def cgcore(model, beta_fraction, sensitivity_fraction, r=R, rl=RL):
    """Return (status, glucose, insulin_total, insulin_specific, cpeptide).

    The model argument is unused.
    """
    try:
        a = math.pow(beta_fraction, 0.25)
        b = math.pow(beta_fraction, 0.75)
    except ValueError:
        a = b = math.nan
    result = homa(a, b, sensitivity_fraction, r, rl)
    status, *values = result
    if status > 0:
        return (status, SENTINEL, SENTINEL, SENTINEL, SENTINEL)
    return (status, values[1], values[2] + values[10], values[2], values[4])


