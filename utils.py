@dataclass(frozen=True)
class HomaXResult:
    """homaX beta-cell function (%), sensitivity (%), and resistance."""
    percent_b: float
    percent_s: float
    ir: float

    def as_dict(self) -> dict[str, float]:
        return {"homaX_%B": self.percent_b, "homaX_%S": self.percent_s,
                "homaX_IR": self.ir}


class HomaXCalculationError(ArithmeticError):
    """homaX calculation failed."""
    def __init__(self, status: int):
        self.status = status
        super().__init__(f"homaX calculation failed (core status {status})")


def _finite_number(value, name):
    if isinstance(value, bool):
        raise ValueError(f"{name} must be a finite number, not a boolean")
    try:
        value = float(value)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"{name} must be a finite number") from exc
    if not math.isfinite(value):
        raise ValueError(f"{name} must be finite")
    return value


def _unit(value):
    return str(value).strip().lower().replace("µ", "u").replace("μ", "u").replace(" ", "")


def homaX(glucose, hormone, *, hormone_type="insulin",
          glucose_unit="mmol/L", hormone_unit=None,
          hormone_conversion_factor=None, check_ranges=True) -> HomaXResult:
    """Calculate homaX beta-cell function, insulin sensitivity, and resistance.

    Arguments:
        glucose, hormone: fasting concentrations. Defaults are mmol/L for
            glucose, pmol/L for insulin, and nmol/L for C-peptide.
        hormone_type: "insulin", "specific_insulin", or "c_peptide".
        glucose_unit: "mmol/L" or "mg/dL" (converted by multiplying by 0.0555).
        hormone_unit: "pmol/L" or "uU/mL" for insulin; "nmol/L" or "ng/mL"
            for C-peptide. None selects the SI unit.
        hormone_conversion_factor: optional multiplier to SI units.
            Defaults: insulin 6.945, specific insulin 6.85, C-peptide 0.333.
        check_ranges: check SI input ranges after conversion (default True):
            glucose 3–25, insulin 20–400, specific insulin 20–300,
            C-peptide 0.2–3.5.

    Returns:
        HomaXResult with percent_b and percent_s rounded to one decimal,
        and ir = 100 / percent_s.

    Raises:
        ValueError: invalid input, unit, or range.
        HomaXCalculationError: calculation failed.
    """
    glucose = _finite_number(glucose, "glucose")
    hormone = _finite_number(hormone, "hormone")
    kind = str(hormone_type).strip().lower().replace("-", "_").replace(" ", "_")
    modes = {"insulin": -1, "specific_insulin": 0, "c_peptide": 1}
    if kind not in modes:
        raise ValueError("hormone_type must be insulin, specific_insulin, or c_peptide")
    mode = modes[kind]
    gunit = _unit(glucose_unit)
    if gunit == "mg/dl":
        glucose *= 0.0555
    elif gunit != "mmol/l":
        raise ValueError("glucose_unit must be mmol/L or mg/dL")

    si_unit = "nmol/l" if mode == 1 else "pmol/l"
    hunit = si_unit if hormone_unit is None else _unit(hormone_unit)
    alternate_units = ("ng/ml",) if mode == 1 else ("uu/ml", "uiu/ml", "miu/l")
    if hunit == si_unit:
        if hormone_conversion_factor is not None:
            raise ValueError("hormone_conversion_factor requires a non-SI hormone unit")
    elif hunit in alternate_units:
        factor = (6.945, 6.85, 0.333)[mode + 1]
        if hormone_conversion_factor is not None:
            factor = _finite_number(hormone_conversion_factor, "hormone_conversion_factor")
        if factor <= 0.0:
            raise ValueError("hormone_conversion_factor must be positive")
        hormone *= factor
    else:
        raise ValueError(f"Unsupported hormone_unit for {kind}: {hormone_unit!r}")

    if not math.isfinite(glucose) or not math.isfinite(hormone):
        raise ValueError("Unit conversion produced a non-finite value")
    if check_ranges:
        low, high = HORMIN[mode + 1], HORMAX[mode + 1]
        if not GLUMIN <= glucose <= GLUMAX:
            raise ValueError(f"glucose must be {GLUMIN:g}..{GLUMAX:g} mmol/L for this v2.2.3 range check")
        if not low <= hormone <= high:
            raise ValueError(f"{kind} must be {low:g}..{high:g} {si_unit}")
    try:
        status, beta, sensitivity = calculate_core(glucose, hormone, mode)
    except (OverflowError, ZeroDivisionError) as exc:
        raise HomaXCalculationError(-100) from exc
    if status != 0:
        raise HomaXCalculationError(status)
    if not (math.isfinite(beta) and math.isfinite(sensitivity) and sensitivity > 0):
        raise HomaXCalculationError(-101)
    return HomaXResult(beta, sensitivity, 100.0 / sensitivity)


