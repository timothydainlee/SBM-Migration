    if not math.isfinite(glucose) or not math.isfinite(hormone):
        raise ValueError("glucose and hormone must be finite")
    if glucose <= 0.0 or hormone <= 0.0:
        return -6, -999.0, -999.0
    if glucose >= 25.2:
        return -7, 0.0, -999.0
    if forward is None:
        forward = forward_core
    status, b, s = _solve_point(glucose, hormone, mode, forward)
    if status == 0:
        return 0, legacy_round(b, 1), legacy_round(s, 1)

    # Try surrounding 0.1-grid points while retaining the failure status.
    original_status = status
    rg = legacy_round(glucose, 1)
    rh = legacy_round(hormone, 1)
    glo = rg - 0.1 if glucose < rg else rg
    ghi = rg + 0.1 if glucose > rg else rg
    hlo = rh - 0.1 if hormone < rh else rh
    hhi = rh + 0.1 if hormone > rh else rh
    corners = []
    for g, h in ((glo, hlo), (ghi, hlo), (glo, hhi), (ghi, hhi)):
        status, b, s = _solve_point(legacy_round(g, 1), legacy_round(h, 1), mode, forward)
        if status != 0:
            return original_status, -999.0, -999.0
        corners.append((b, s))
    gx = (glucose - glo) / 0.1
    gy = (hormone - hlo) / 0.1
    nx = (glo + 0.1 - glucose) / 0.1
    ny = (hlo + 0.1 - hormone) / 0.1
    def interpolate(column):
        return ((gx * ny * corners[1][column] + gx * gy * corners[3][column])
                + nx * gy * corners[2][column]) + nx * ny * corners[0][column]
    return original_status, legacy_round(interpolate(0), 1), legacy_round(interpolate(1), 1)

